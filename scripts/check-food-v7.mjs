import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {assessFoodService,evaluateFoodLocations,findFoodLocation,findFoodService,validateFoodDataset} from "../lib/food-truth.mjs";
const read=async p=>JSON.parse(await readFile(new URL("../"+p,import.meta.url),"utf8"));
const data=await read("data/food-offerings.json");
const venues=await read("data/venues.json");
const issues=validateFoodDataset(data,{venueIds:new Set(venues.map(v=>v.id))});
assert.deepEqual(issues,[],"Food data contract problems");
assert.equal(data.locations.length,5);
assert.equal(data.locations.reduce((n,l)=>n+l.services.length,0),7);
assert.equal(findFoodLocation(data,"brys-estate").kind,"winery");
assert.equal(findFoodService(data,"peninsula-grill-dining").mealType,"FULL_MEAL");
const base={data,date:"2026-10-20",startTime:"12:00",durationMinutes:60,partySize:2,asOf:"2026-10-13"};
const check=(loc,id,state,extra={})=>{
 const result=assessFoodService({...base,locationId:loc,serviceId:id,...extra});
 assert.equal(result.state,state,loc+"/"+id+" "+JSON.stringify(extra)+": "+result.reason);
 assert.equal(result.bookingAvailability,"NOT_CHECKED");
 assert.equal(result.reserved,false);
 assert.ok(["REJECT","CONDITIONAL","CANDIDATE"].includes(result.fit));
 return result;
};
const brys=check("brys-estate","brys-seated-food","CALL_TO_CONFIRM");
assert.equal(brys.mealType,"SUBSTANTIAL");
assert.equal(brys.fit,"CONDITIONAL");
check("brys-estate","brys-lawn-snacks","NOT_FULL_MEAL");
check("bonobo","bonobo-small-plates","KITCHEN_CLOSED");
check("bonobo","bonobo-small-plates","NOT_FULL_MEAL",{startTime:"14:00"});
check("bonobo","bonobo-reservable-pairing","NOT_FULL_MEAL");
check("bonobo","bonobo-reservable-pairing","BOOKING_REQUIRED",{requestedMeal:"PAIRING"});
check("jolly-pumpkin","jolly-restaurant","SOURCE_CONFLICT");
check("jolly-pumpkin","jolly-restaurant","SOURCE_CONFLICT",{startTime:"16:00"});
const pg=check("peninsula-grill","peninsula-grill-dining","SOURCE_CONFLICT");
assert.equal(pg.conflictingSources.length,3);
check("peninsula-grill","peninsula-grill-dining","CALL_TO_CONFIRM",{date:"2026-10-23"});
check("peninsula-grill","peninsula-grill-dining","VENUE_TYPE_MISMATCH",{strictWinery:true});
check("jolly-pumpkin","jolly-restaurant","CALL_TO_CONFIRM",{date:"2026-10-24"});
check("chateau-chantal","chantal-charcuterie","NOT_FULL_MEAL");
check("brys-estate","brys-seated-food","SOURCE_STALE",{asOf:"2026-11-15"});
check("brys-estate","brys-seated-food","NEEDS_INPUT",{date:undefined});
check("brys-estate","brys-seated-food","NEEDS_INPUT",{date:"2026-02-30"});
check("brys-estate","brys-seated-food","NEEDS_INPUT",{startTime:undefined});
check("brys-estate","brys-seated-food","NEEDS_INPUT",{durationMinutes:0});
check("brys-estate","brys-seated-food","PARTY_LIMIT",{partySize:7});
check("bonobo","peninsula-grill-dining","UNKNOWN_SERVICE");
check("made-up","made-up","UNKNOWN_SERVICE");
assert.ok(pg.conflictingSources.every(url=>url.startsWith("https://")));
const results=evaluateFoodLocations({...base});
assert.equal(results.length,7);
assert.ok(results.every(x=>x.fit!=="CANDIDATE"),"No fully verified lunch supported by the current evidence");
