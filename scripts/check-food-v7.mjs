const place=fixture.locations.find(x=>x.locationId==="jolly-pumpkin");
place.services[0].conflicts=[];
place.services[0].hoursBasis="KITCHEN_EXPLICIT";
place.services[0].hoursScope="PUBLISHED_CURRENT";
place.services[0].dateExceptions=[{date:"2026-10-20",closed:true}];
assert.equal(assessFoodService({...base,data:fixture,locationId:"jolly-pumpkin",serviceId:"jolly-restaurant"}).state,"DATE_EXCEPTION");
place.services[0].dateExceptions=[];
const hypothetical=assessFoodService({...base,data:fixture,locationId:"jolly-pumpkin",serviceId:"jolly-restaurant",startTime:"16:00"});
assert.equal(hypothetical.state,"PUBLISHED_SERVICE_FITS");
assert.equal(hypothetical.bookingAvailability,"NOT_CHECKED");
fixture.locations.push(structuredClone(fixture.locations[0]));
assert.ok(validateFoodDataset(fixture).some(x=>x.includes("duplicate")));
